#!/usr/bin/env python3
"""Paced, read-only NavMe public-visitor API check, capped at 60 active visitors.

The default command prints its plan without making requests. --execute performs
the explicitly authorized production check. This does not instantiate 60 browser
or Matterport renderers and does not measure their third-party asset traffic.
Only the optional published-route query uses POST; it cannot modify records.
"""
from __future__ import annotations

import argparse
import asyncio
import collections
from datetime import datetime, timezone
import hashlib
import json
import math
from pathlib import Path
import random
import time
from urllib.parse import quote, urlsplit


SLUG = "uncc-main-campus"
PRODUCTION = "https://wayfinding.navme.space"
API = "/api/v1/public/"
STAGES = (1, 10, 25, 40, 60)


def percentile(values, quantile):
    if not values:
        return None
    values = sorted(values)
    point = (len(values) - 1) * quantile
    lo = int(point)
    hi = min(lo + 1, len(values) - 1)
    return round(values[lo] + (values[hi] - values[lo]) * (point - lo), 2)


def latency(values):
    return {"count": len(values), "p50_ms": percentile(values, .5),
            "p95_ms": percentile(values, .95), "p99_ms": percentile(values, .99),
            "max_ms": round(max(values), 2) if values else None}


def allowed_base(value, allow_loopback=False):
    parts = urlsplit(value)
    if parts.username or parts.password or parts.query or parts.fragment or parts.path not in ("", "/"):
        raise ValueError("Use a bare origin without credentials, query or path")
    origin = value.rstrip("/")
    if origin == PRODUCTION:
        return origin
    if allow_loopback and parts.scheme == "http" and parts.hostname in {"localhost", "127.0.0.1", "::1"}:
        return origin
    raise ValueError("Only the authorized production origin or explicit local loopback is permitted")


def public_path(path):
    # IDs are public location identifiers but need not appear in network reports.
    if "/camera-viewpoints/" in path:
        return path.split("/camera-viewpoints/", 1)[0] + "/camera-viewpoints/:location_id"
    return path


def route_evidence(data):
    """A zero-length/single-node response is not a meaningful route diagnostic."""
    length = data.get("length_m") if isinstance(data, dict) else None
    nodes = data.get("nodes") if isinstance(data, dict) else None
    if (isinstance(length, bool) or not isinstance(length, (int, float))
            or not math.isfinite(length) or length <= 5 or not isinstance(nodes, list) or len(nodes) < 2):
        return None
    return {"length_m": length, "nodes": len(nodes),
            "response_sha256": hashlib.sha256(json.dumps(data, sort_keys=True, allow_nan=False).encode()).hexdigest()}


class Pacer:
    """Bound aggregate start rate without disguising active visitor counts."""
    def __init__(self, rps):
        self.interval = 1 / rps
        self.next = 0.0
        self.lock = asyncio.Lock()

    async def wait(self):
        async with self.lock:
            now = time.monotonic()
            when = max(now, self.next)
            self.next = when + self.interval
        await asyncio.sleep(max(0, when - now))


class Run:
    def __init__(self, args):
        self.args = args
        self.stop = asyncio.Event()
        self.reason = None
        self.pacer = Pacer(args.max_rps)
        self.samples = []
        self.inflight = 0
        self.peak_inflight = 0
        self.bytes = 0
        self.client = None
        self.report = {
            "schema": "navme.production-visitor-check/v1", "started_utc": utc(),
            "origin": args.base_url, "slug": SLUG,
            "scope": "Paced public API visitors, not simultaneous Matterport/browser renderers",
            "production_load_authorized_by_user": True,
            "constraints": {"max_visitors": 60, "max_rps": args.max_rps,
                            "max_connections": 72, "max_aggregate_response_body_mib": args.max_mib,
                            "new_data_or_admin_writes": False, "cache_clear_or_cache_bust": False},
            "stages": [], "limitations": [
                "HTTP response encoded-body bytes exclude HTTP headers, TLS and retransmissions.",
                "Decoded bytes are the uncompressed application body; they are not user data-plan usage.",
                "No third-party Matterport/photo/font asset requests are generated by this API profile.",
                "No client crash, WebGL loss, iframe reload or physical-device behavior is proven by API success.",
                "Fresh API bootstrap requests are not a browser disk-cache simulation.",
                "Normal public routing runs client-side Recast; optional server-route diagnostics are reported separately.",
            ],
        }

    def halt(self, reason):
        if not self.stop.is_set():
            self.reason = reason
            self.stop.set()

    def save(self):
        self.args.output.parent.mkdir(parents=True, exist_ok=True)
        self.args.output.write_text(json.dumps(self.report, indent=2) + "\n")

    async def request(self, kind, path, *, phase, expected=(200,), payload=None, paced=True):
        if self.stop.is_set():
            return None
        if paced:
            await self.pacer.wait()
        if self.stop.is_set():
            return None
        self.inflight += 1
        self.peak_inflight = max(self.peak_inflight, self.inflight)
        start = time.monotonic()
        row = {"phase": phase, "kind": kind, "path": public_path(path),
               "method": "POST" if payload is not None else "GET"}
        try:
            body = json.dumps(payload, separators=(",", ":")).encode() if payload is not None else None
            response = await self.client.request(row["method"], path, content=body,
                headers={"Content-Type": "application/json"} if body is not None else None)
            wire = response.num_bytes_downloaded
            self.bytes += wire
            row.update(status=response.status_code, expected=response.status_code in expected,
                       encoded_response_body_bytes=wire, decoded_response_body_bytes=len(response.content),
                       request_body_bytes=len(body or b""), http_version=response.http_version,
                       content_encoding=response.headers.get("content-encoding", "identity"),
                       content_type=response.headers.get("content-type", "").split(";", 1)[0],
                       cache_control=response.headers.get("cache-control"),
                       layer=error_layer(response))
            if kind == "server_route_diagnostic" and response.status_code == 200:
                evidence = route_evidence(response.json())
                if not evidence or evidence["response_sha256"] != self.report["server_route_preflight"]["response_sha256"]:
                    row.update(expected=False, layer="route_geometry_mismatch")
                    self.halt("route_geometry_mismatch")
            if self.bytes > self.args.max_mib * 1024 ** 2:
                self.halt("aggregate_response_body_budget_reached")
            return response
        except Exception as exc:
            # Exception strings can contain URLs or headers: record the class only.
            row.update(status=0, expected=False, error_class=type(exc).__name__,
                       encoded_response_body_bytes=None, decoded_response_body_bytes=None)
            return None
        finally:
            row["latency_ms"] = round((time.monotonic() - start) * 1000, 2)
            self.samples.append(row)
            self.inflight -= 1
            phase_rows = [x for x in self.samples if x["phase"] == phase]
            recent = phase_rows[-100:]
            failures = sum(not x["expected"] for x in recent)
            if len(recent) >= 20 and failures / len(recent) >= .01:
                self.halt("unexpected_response_or_transport_failure_gate")

    async def json_get(self, kind, path):
        response = await self.request(kind, path, phase="discovery")
        if response is None or response.status_code != 200:
            self.halt("discovery_failed_" + kind)
            raise RuntimeError("Public discovery failed: " + kind)
        return response.json()

    async def discover(self):
        manifest = await self.json_get("manifest", API + "venues/all/manifest.json")
        building = next((b for b in manifest.get("buildings", []) if b.get("slug") == SLUG), None)
        if not building:
            raise RuntimeError("UNC is absent from the current public manifest")
        config = await self.json_get("config", API + f"buildings/{SLUG}/data/config.json")
        view = await self.json_get("viewer_data", API + f"dashboard/buildings/{SLUG}/viewer-data")
        if view.get("building_slug") != SLUG or not isinstance(view.get("pois"), list) or not view["pois"]:
            raise RuntimeError("Invalid published viewer data")
        self.poi_ids = [str(p["id"]) for p in view["pois"] if p.get("id") is not None]
        self.report["publication"] = {"version": building.get("version"), "pois": len(self.poi_ids),
            "categories": len(view.get("categories") or []), "model_id": config.get("matterport_model_id"),
            "manifest_response_sha256": hashlib.sha256(json.dumps(manifest, sort_keys=True).encode()).hexdigest()}
        self.bootstrap = [
            ("landing_html", "/unc-charlotte", (200,)),
            ("manifest", API + "venues/all/manifest.json", (200,)),
            ("config", API + f"buildings/{SLUG}/data/config.json", (200,)),
            ("viewer_data", API + f"dashboard/buildings/{SLUG}/viewer-data", (200,)),
            ("floor_metadata", API + f"buildings/{SLUG}/navme-floors", (200,)),
            ("matterport_config", API + f"buildings/{SLUG}/matterport", (200,)),
            ("shops", API + f"buildings/{SLUG}/shops", (200,)),
            ("ar_reference", API + f"buildings/{SLUG}/ar-experience-ref", (200,)),
            ("translations", API + f"buildings/{SLUG}/translations", (200,)),
            ("media_panels", API + f"buildings/{SLUG}/data/media_panels.json", (200, 404)),
            ("navmesh_resolver", API + f"dashboard/buildings/{SLUG}/navmesh-url", (200,)),
        ]
        if self.args.download_navmesh:
            mesh = await self.json_get("navmesh_resolver", API + f"dashboard/buildings/{SLUG}/navmesh-url")
            url = urlsplit(mesh.get("url", ""))
            if url.netloc and (url.scheme + "://" + url.netloc) != self.args.base_url:
                raise RuntimeError("Binary replay only permits same-origin navmesh; capture external bytes in browser instead")
            if not url.path.startswith("/") or url.query or url.fragment:
                raise RuntimeError("Unexpected navmesh URL")
            self.bootstrap.append(("navmesh_binary", url.path, (200,)))
        self.route_pair = None
        if self.args.include_server_route:
            pois = await self.json_get("published_pois", API + f"buildings/{SLUG}/data/pois.json")
            candidates = [p["id"] for p in pois.get("pois", []) if p.get("id") and p.get("nearest_node")]
            # Deterministic spread, no more than eight query-only attempts. Do
            # not count two labels snapped to the same point as a route pass.
            pairs = []
            for index in range(min(8, len(candidates))):
                a = index * len(candidates) // 8
                b = (a + max(1, len(candidates) // 2)) % len(candidates)
                if a != b and (a, b) not in pairs:
                    pairs.append((a, b))
            for a, b in pairs:
                pair = {"from_key": candidates[a], "to_key": candidates[b], "step_free": False}
                response = await self.request("server_route_preflight", API + f"buildings/{SLUG}/route",
                                              phase="discovery", expected=(200, 404), payload=pair)
                if response is not None and response.status_code == 200:
                    evidence = route_evidence(response.json())
                    if evidence:
                        self.route_pair = pair
                        self.report["server_route_preflight"] = evidence
                        break
            if not self.route_pair:
                raise RuntimeError("No valid optional published server-route pair found")
        self.report["profile"] = {"bootstrap_requests_per_visitor": len(self.bootstrap),
            "binary_navmesh_download_each_visitor": self.args.download_navmesh,
            "server_route_diagnostic_each_action": self.route_pair is not None,
            "warm_action": "one fresh camera-viewpoint GET per3–7s;200/404 both valid public states",
            "think_seconds": [3, 7], "ramp_spread_seconds": 5}

    async def external_stop_monitor(self):
        while not self.stop.is_set():
            if self.args.stop_file and self.args.stop_file.exists():
                self.halt("external_monitor_stop_file")
                return
            await asyncio.sleep(.5)

    async def stage(self, visitors):
        phase = f"visitors_{visitors}"
        before = len(self.samples)
        started = time.monotonic()
        self.peak_inflight = 0
        probe_rows = []
        finished = asyncio.Event()
        async def probe():
            while not finished.is_set() and not self.stop.is_set():
                response = await self.request("liveness_probe", "/api/live", phase=phase, paced=False)
                status = response.status_code if response is not None else 0
                probe_rows.append(status)
                if status != 200:
                    self.halt("liveness_probe_failed")
                    break
                try:
                    await asyncio.wait_for(finished.wait(), timeout=2)
                except asyncio.TimeoutError:
                    pass
        async def bootstrap(index):
            rnd = random.Random(visitors * 1000 + index)
            await asyncio.sleep(rnd.uniform(0, 5) if visitors > 1 else 0)
            for kind, path, expected in self.bootstrap:
                await self.request(kind, path, phase=phase, expected=expected)
                await asyncio.sleep(rnd.uniform(.1, .25))
                if self.stop.is_set():
                    return
        async def action(index, deadline):
            rnd = random.Random(visitors * 10000 + index)
            while not self.stop.is_set() and time.monotonic() < deadline:
                await asyncio.sleep(rnd.uniform(3, 7))
                if self.stop.is_set() or time.monotonic() >= deadline:
                    break
                pid = self.poi_ids[rnd.randrange(len(self.poi_ids))]
                await self.request("poi_viewpoint", API + f"buildings/{SLUG}/camera-viewpoints/" + quote(pid, safe=""),
                                   phase=phase, expected=(200, 404))
                if self.route_pair:
                    await self.request("server_route_diagnostic", API + f"buildings/{SLUG}/route",
                                       phase=phase, payload=self.route_pair)
        monitor = asyncio.create_task(probe())
        await asyncio.gather(*(bootstrap(i) for i in range(visitors)))
        loaded_at = time.monotonic()
        duration = self.args.soak_seconds if visitors == 60 else self.args.ramp_seconds
        if not self.stop.is_set():
            await asyncio.gather(*(action(i, loaded_at + duration) for i in range(visitors)))
        finished.set()
        await monitor
        recovered = []
        # Recovery probes are useful even after a stop, but do not override it.
        for _ in range(3):
            t = time.monotonic()
            try:
                response = await self.client.get("/api/health")
                recovered.append({"status": response.status_code, "ms": round((time.monotonic()-t)*1000, 2)})
            except Exception as exc:
                recovered.append({"status": 0, "error_class": type(exc).__name__})
            await asyncio.sleep(.4)
        if any(row["status"] != 200 for row in recovered):
            self.halt("recovery_readiness_failed")
        rows = self.samples[before:]
        failures = [r for r in rows if not r["expected"]]
        if rows and len(failures) / len(rows) >= .01:
            self.halt("stage_failure_rate_gate")
        result = {"concurrent_visitors": visitors, "scope": "API visitor tasks; not browser/Matterport instances",
            "bootstrap_seconds": round(loaded_at-started, 2), "loaded_session_seconds_requested": duration,
            "wall_seconds": round(time.monotonic()-started, 2), "peak_inflight_http_requests": self.peak_inflight,
            "requests": len(rows), "unexpected_failures": len(failures),
            "failure_percent": round(100*len(failures)/max(1, len(rows)), 3),
            "status_counts": dict(collections.Counter(str(r["status"]) for r in rows)),
            "latency": latency([r["latency_ms"] for r in rows]),
            "by_kind": summarize(rows, "kind"), "network_by_path": summarize(rows, "path"),
            "liveness_probe_statuses": dict(collections.Counter(map(str, probe_rows))),
            "recovery_readiness": recovered,
            "errors": [{k:r[k] for k in ("kind", "status", "layer", "error_class") if k in r} for r in failures[:20]],
            "completed_without_stop": not self.stop.is_set(),
            "browser_model_or_iframe_reload_observed": "NOT_MEASURED_BY_API_TEST"}
        self.report["stages"].append(result)
        self.save()
        print(json.dumps({"visitors": visitors, "failures": len(failures),
                          "p95_ms": result["latency"]["p95_ms"], "stop": self.reason}), flush=True)
        return result

    async def execute(self):
        import httpx
        limits = httpx.Limits(max_connections=72, max_keepalive_connections=60)
        async with httpx.AsyncClient(base_url=self.args.base_url, timeout=20, limits=limits,
                                    headers={"Accept-Encoding": "gzip, deflate", "User-Agent": "NavMe-authorized-visitor-check/1"},
                                    follow_redirects=False, trust_env=False) as client:
            self.client = client
            watcher = asyncio.create_task(self.external_stop_monitor())
            try:
                await self.discover()
                self.save()
                for visitors in self.args.stages:
                    if self.stop.is_set():
                        break
                    await self.stage(visitors)
                    await asyncio.sleep(2)
            except Exception as exc:
                self.halt("run_exception_" + type(exc).__name__)
                self.report["fatal_error_class"] = type(exc).__name__
            finally:
                watcher.cancel()
                await asyncio.gather(watcher, return_exceptions=True)
        self.report.update(finished_utc=utc(), stop_reason=self.reason,
            all_requests=len(self.samples), network_by_path=summarize(self.samples, "path"),
            total_encoded_response_body_bytes=sum(r.get("encoded_response_body_bytes") or 0 for r in self.samples),
            total_decoded_response_body_bytes=sum(r.get("decoded_response_body_bytes") or 0 for r in self.samples),
            failed_requests_with_unknown_transfer_bytes=sum(r.get("encoded_response_body_bytes") is None for r in self.samples),
            passed=not self.stop.is_set() and [r["concurrent_visitors"] for r in self.report["stages"]] == list(self.args.stages))
        self.save()
        return self.report["passed"]


def error_layer(response):
    if response.status_code < 500:
        return None
    if response.status_code == 503 and response.text.strip() == "Service Unavailable":
        return "server_admission"
    try:
        detail = response.json().get("detail")
    except Exception:
        return "other_server_error"
    if detail == "database unavailable":
        return "database"
    if detail == "published data temporarily unavailable":
        return "publication_preparation"
    return "other_server_error"


def summarize(rows, key):
    groups = collections.defaultdict(list)
    for row in rows:
        groups[row[key]].append(row)
    return {group: {"requests": len(items), "unexpected_failures": sum(not r["expected"] for r in items),
        "status_counts": dict(collections.Counter(str(r["status"]) for r in items)),
        "encoded_body_bytes": sum(r.get("encoded_response_body_bytes") or 0 for r in items),
        "decoded_body_bytes": sum(r.get("decoded_response_body_bytes") or 0 for r in items),
        "unknown_transfer_requests": sum(r.get("encoded_response_body_bytes") is None for r in items),
        "latency": latency([r["latency_ms"] for r in items])} for group, items in groups.items()}


def utc():
    return datetime.now(timezone.utc).isoformat()


def parse_args():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--base-url", default=PRODUCTION)
    parser.add_argument("--allow-loopback", action="store_true")
    parser.add_argument("--execute", action="store_true")
    parser.add_argument("--stages", type=int, nargs="+", default=list(STAGES))
    parser.add_argument("--soak-seconds", type=int, default=120)
    parser.add_argument("--ramp-seconds", type=int, default=10)
    parser.add_argument("--max-rps", type=float, default=25)
    parser.add_argument("--max-mib", type=int, default=256)
    parser.add_argument("--download-navmesh", action="store_true")
    parser.add_argument("--include-server-route", action="store_true")
    parser.add_argument("--stop-file", type=Path)
    parser.add_argument("--output", type=Path, default=Path("docs/evidence/uncc-production/visitors.json"))
    args = parser.parse_args()
    try:
        args.base_url = allowed_base(args.base_url, args.allow_loopback)
    except ValueError as exc:
        parser.error(str(exc))
    if any(n not in STAGES for n in args.stages) or args.stages != sorted(set(args.stages)):
        parser.error("Stages must be increasing unique values drawn from1,10,25,40,60")
    if not 1 <= args.soak_seconds <= 180 or not 0 <= args.ramp_seconds <= 30:
        parser.error("Soak must be1–180seconds; ramp0–30seconds")
    if not 1 <= args.max_rps <= 30 or not 1 <= args.max_mib <= 512:
        parser.error("Request rate must be1–30RPS and body budget1–512MiB")
    return args


if __name__ == "__main__":
    args = parse_args()
    if not args.execute:
        print(json.dumps({"dry_run": True, "origin": args.base_url, "stages": args.stages,
            "soak_seconds_at_60": args.soak_seconds, "max_rps": args.max_rps,
            "download_navmesh": args.download_navmesh, "include_server_route_diagnostic": args.include_server_route,
            "network_requests_made": 0}, indent=2))
    else:
        raise SystemExit(0 if asyncio.run(Run(args).execute()) else 1)
